#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
将 MaxKey 的 MySQL 导出脚本转换为 KingbaseES(兼容 PostgreSQL) 可执行脚本。

用法:
    python3 sql/kingbase/convert_from_mysql.py \
        sql/v4.2.0/maxkey.sql \
        sql/kingbase/maxkey.sql

转换内容:
    * 反引号 -> 无引号(标识符统一小写)
    * ENGINE / CHARSET / COLLATE / ROW_FORMAT / LOCK TABLES / /*!...*/  -> 移除
    * datetime -> timestamp, tinyint -> smallint, int -> integer, longtext -> text, blob -> bytea
    * 列 COMMENT / 表 COMMENT -> COMMENT ON COLUMN / COMMENT ON TABLE
    * UNIQUE KEY -> CONSTRAINT ... UNIQUE, KEY -> CREATE INDEX
    * AUTO_INCREMENT -> GENERATED BY DEFAULT AS IDENTITY (+ 数据导入后重置序列)
    * MySQL 字符串转义(\\' \\\\ \\n \\r \\0 \\Z) -> PostgreSQL E'' 字面量
    * _binary '...' -> decode('..', 'hex')
    * INSERT 补充显式列名，避免列顺序/类型变化带来的隐患
"""

import re
import sys

IDENT = r'`([^`]+)`'

# MySQL -> Kingbase/PostgreSQL 数据类型映射
TYPE_MAP = {
    # 保持不变的
    'varchar': 'varchar',
    'char': 'char',
    'decimal': 'decimal',
    'numeric': 'numeric',
    'date': 'date',
    'time': 'time',
    'boolean': 'boolean',
    'bit': 'bit',
    # 需要转换的
    'datetime': 'timestamp',
    'timestamp': 'timestamp',
    'tinyint': 'smallint',
    'smallint': 'smallint',
    'mediumint': 'integer',
    'int': 'integer',
    'integer': 'integer',
    'bigint': 'bigint',
    'text': 'text',
    'tinytext': 'text',
    'mediumtext': 'text',
    'longtext': 'text',
    'blob': 'bytea',
    'tinyblob': 'bytea',
    'mediumblob': 'bytea',
    'longblob': 'bytea',
    'varbinary': 'bytea',
    'double': 'double precision',
    'float': 'real',
}

BYTEA_TYPES = {'bytea'}

# KingbaseES MySQL 兼容模式下的保留字(catcode=R/T)，与 MaxKey 表结构冲突的需加双引号。
# 完整清单可通过 select word from sys_get_keywords() where catcode in ('R','T'); 获取
RESERVED = set("""
all analyse analyze and any array as asc asymmetric authorization begin binary both case cast check
collate collation column concurrently connect connect_by_root constraint create cross current_catalog
current_date current_role current_schema current_time current_timestamp current_user cursor default
deferrable desc distinct distinctrow div do else enclosed end escaped except false fetch for foreign
freeze from full grant group having if ignore ilike in infile initially inner int2 int4 int8 intersect
into is isnull join lateral leading left like limit localtime localtimestamp loop minus mod natural
nocycle not null nvl nvl2 offset on online only optionally or order outer outfile overlaps placing
primary prior recursive references regexp repeat return returning right rlike rownum select
session_user sessiontimezone similar some sql_calc_found_rows start starting symmetric
sys_connect_by_path systimestamp table tablesample terminated then tinyint to top trailing true union
unique unix_timestamp user using varbinary variadic verbose when where while window with xor
""".split())


def qident(name):
    """保留字加双引号，其余保持原样"""
    if name.lower() in RESERVED:
        return '"%s"' % name
    return name

# MySQL 反斜杠转义表
ESCAPE = {
    ord('0'): 0x00, ord('b'): 0x08, ord('n'): 0x0a, ord('r'): 0x0d,
    ord('t'): 0x09, ord('Z'): 0x1a, ord('\\'): 0x5c, ord("'"): 0x27,
    ord('"'): 0x22,
}

warnings = []


def warn(msg):
    warnings.append(msg)


class Table:
    def __init__(self, name):
        self.name = name
        self.columns = []          # [(col_name, is_bytea)]
        self.column_comments = []  # [(col_name, comment)]
        self.table_comment = None
        self.indexes = []          # [(idx_name, cols)]
        self.identity_col = None
        self.rows = []             # [[value, ...], ...]


def read_quoted(buf, i):
    """从 buf[i]==b"'" 开始读取 MySQL 字符串，返回 (bytes, 结束位置)"""
    i += 1
    out = bytearray()
    n = len(buf)
    while i < n:
        c = buf[i]
        if c == 0x5c:  # backslash
            if i + 1 >= n:
                break
            nxt = buf[i + 1]
            out.append(ESCAPE.get(nxt, nxt))
            i += 2
        elif c == 0x27:  # '
            if i + 1 < n and buf[i + 1] == 0x27:
                out.append(0x27)
                i += 2
            else:
                return bytes(out), i + 1
        else:
            out.append(c)
            i += 1
    raise ValueError('unterminated string literal')


def parse_insert_values(buf):
    """解析 VALUES 之后的 (...),(...) 部分，返回行列表。
    每个值: ('null',None) / ('num',b'..') / ('str',bytes) / ('bin',bytes)
    """
    rows = []
    i = 0
    n = len(buf)
    while i < n:
        # 定位下一个 '('
        while i < n and buf[i:i + 1] != b'(':
            i += 1
        if i >= n:
            break
        i += 1
        row = []
        while True:
            while i < n and buf[i:i + 1] in (b' ', b'\n', b'\r', b'\t'):
                i += 1
            if i >= n:
                raise ValueError('unexpected end of insert')
            if buf[i:i + 7].upper() == b'_BINARY':
                i += 7
                while i < n and buf[i:i + 1] in (b' ', b'\n', b'\r', b'\t'):
                    i += 1
                raw, i = read_quoted(buf, i)
                row.append(('bin', raw))
            elif buf[i:i + 1] == b"'":
                raw, i = read_quoted(buf, i)
                row.append(('str', raw))
            elif buf[i:i + 4].upper() == b'NULL':
                i += 4
                row.append(('null', None))
            else:
                start = i
                while i < n and buf[i:i + 1] not in (b',', b')'):
                    i += 1
                row.append(('num', buf[start:i].strip()))
            while i < n and buf[i:i + 1] in (b' ', b'\n', b'\r', b'\t'):
                i += 1
            if i >= n:
                raise ValueError('unexpected end of row')
            if buf[i:i + 1] == b',':
                i += 1
                continue
            if buf[i:i + 1] == b')':
                i += 1
                break
            raise ValueError('unexpected char %r at %d' % (buf[i:i + 1], i))
        rows.append(row)
        while i < n and buf[i:i + 1] in (b',', b' ', b'\n', b'\r', b'\t'):
            i += 1
    return rows


def pg_text(raw):
    """bytes -> PostgreSQL E'...' 字面量"""
    raw = raw.replace(b'\x00', b'')
    try:
        text = raw.decode('utf-8')
    except UnicodeDecodeError:
        text = raw.decode('latin-1')
        warn('文本字段包含非 UTF-8 字节，已按 latin-1 解码')
    return "E'" + text.replace('\\', '\\\\').replace("'", "''") + "'"


def pg_value(kind, val, is_bytea):
    if kind == 'null':
        return 'NULL'
    if kind == 'bin':
        return "E'\\\\x%s'::bytea" % val.hex()
    if kind == 'num':
        return val.decode('ascii')
    if is_bytea:
        return "E'\\\\x%s'::bytea" % val.hex()
    return pg_text(val)


def parse_column(line):
    """解析一行列定义，返回 (col_name, type, rest) 或 None"""
    m = re.match(r'^\s*`([^`]+)`\s+([A-Za-z]+)(\s*\([0-9,]+\))?\s*(.*?),?\s*$', line)
    if not m:
        return None
    name, base_type, _, rest = m.group(1), m.group(2).lower(), m.group(3), m.group(4)
    return name.lower(), base_type, rest


def convert_ddl_block(lines, table):
    """处理 CREATE TABLE 的括号内各行"""
    body = []
    for line in lines:
        stripped = line.strip().rstrip(',')
        if not stripped:
            continue
        upper = stripped.upper()

        if upper.startswith('PRIMARY KEY'):
            cols = re.findall(IDENT, stripped)
            body.append('PRIMARY KEY (%s)' % ', '.join(qident(c.lower()) for c in cols))
            continue

        if upper.startswith('UNIQUE KEY'):
            m = re.match(r'UNIQUE KEY `([^`]+)` \((.*)\)', stripped)
            if m:
                cols = ', '.join(qident(c.lower()) for c in re.findall(IDENT, m.group(2)))
                body.append('CONSTRAINT %s UNIQUE (%s)' % (m.group(1).lower(), cols))
            continue

        if upper.startswith('KEY '):
            m = re.match(r'KEY `([^`]+)` \((.*)\)', stripped)
            if m:
                cols = ', '.join(qident(c.lower()) for c in re.findall(IDENT, m.group(2)))
                table.indexes.append((m.group(1).lower(), cols))
            continue

        if upper.startswith('FULLTEXT') or upper.startswith('CONSTRAINT') or upper.startswith('INDEX '):
            warn('忽略未支持的索引定义: %s (表 %s)' % (stripped, table.name))
            continue

        # 列定义
        m = re.match(r'^\s*`([^`]+)`\s+([A-Za-z]+)(\([0-9,]+\))?\s*(.*)$', stripped)
        if not m:
            warn('无法解析的 DDL 行: %s (表 %s)' % (stripped, table.name))
            continue
        col, base_type, size, rest = m.group(1).lower(), m.group(2).lower(), m.group(3) or '', m.group(4) or ''

        pg_type = TYPE_MAP.get(base_type, base_type)
        if base_type not in TYPE_MAP:
            warn('未映射的类型 %s (表 %s 列 %s)' % (base_type, table.name, col))

        # 注释
        cm = re.search(r"COMMENT\s+'((?:[^'\\]|\\.|'')*)'", rest)
        if cm:
            table.column_comments.append((col, cm.group(1)))
            rest = rest[:cm.start()] + rest[cm.end():]

        auto_inc = 'AUTO_INCREMENT' in rest.upper()
        rest = re.sub(r'\bAUTO_INCREMENT\b', '', rest, flags=re.I)
        rest = re.sub(r'\bCHARACTER\s+SET\s+\w+', '', rest, flags=re.I)
        rest = re.sub(r'\bCOLLATE\s+\w+', '', rest, flags=re.I)
        rest = re.sub(r'\s+', ' ', rest).strip()

        parts = ['%s %s%s' % (qident(col), pg_type, size)]
        if auto_inc:
            parts.append('GENERATED BY DEFAULT AS IDENTITY')
            table.identity_col = col
        else:
            if 'NOT NULL' in rest.upper():
                parts.append('NOT NULL')
            dm = re.search(r'DEFAULT\s+(\'[^\']*\'|[\w().]+)', rest, flags=re.I)
            if dm:
                default = dm.group(1)
                if default.upper() in ('CURRENT_TIMESTAMP', 'CURRENT_TIMESTAMP()'):
                    default = 'CURRENT_TIMESTAMP'
                parts.append('DEFAULT %s' % default)
        body.append(' '.join(parts))
        table.columns.append((col, pg_type in BYTEA_TYPES))

    return body


def main(src, dst):
    with open(src, 'rb') as f:
        content = f.read()
    content = content.replace(b'\r\n', b'\n').replace(b'\r', b'\n')

    tables = {}
    order = []
    out = []

    lines = content.split(b'\n')
    i = 0
    n = len(lines)
    while i < n:
        raw_line = lines[i]
        line = raw_line.decode('utf-8', errors='replace')
        stripped = line.strip()

        if (not stripped
                or stripped.startswith('--')
                or stripped.startswith('/*!')
                or stripped.startswith('LOCK TABLES')
                or stripped.startswith('UNLOCK TABLES')):
            i += 1
            continue

        m = re.match(r'DROP TABLE IF EXISTS `([^`]+)`;', stripped)
        if m:
            out.append('DROP TABLE IF EXISTS %s CASCADE;' % m.group(1).lower())
            i += 1
            continue

        m = re.match(r'CREATE TABLE `([^`]+)` \($', stripped)
        if m:
            name = m.group(1).lower()
            table = Table(name)
            tables[name] = table
            order.append(name)
            i += 1
            body_lines = []
            while i < n:
                cur = lines[i].decode('utf-8', errors='replace')
                if cur.strip().startswith(')'):
                    tail = cur.strip()
                    cm = re.search(r"COMMENT='((?:[^'\\]|\\.)*)'", tail)
                    if cm:
                        table.table_comment = cm.group(1)
                    i += 1
                    break
                body_lines.append(cur)
                i += 1

            body = convert_ddl_block(body_lines, table)
            ddl = ['CREATE TABLE %s (' % name]
            ddl.append(',\n'.join('    ' + b for b in body))
            ddl.append(');')
            out.append('\n'.join(ddl))
            if table.table_comment:
                out.append("COMMENT ON TABLE %s IS E'%s';" % (name, table.table_comment.replace("'", "''")))
            for col, comment in table.column_comments:
                out.append("COMMENT ON COLUMN %s.%s IS E'%s';" % (name, qident(col), comment.replace("'", "''")))
            for idx, cols in table.indexes:
                out.append('CREATE INDEX %s_%s ON %s (%s);' % (name, idx, name, cols))
            continue

        m = re.match(r'INSERT INTO `([^`]+)` VALUES ', line)
        if m:
            name = m.group(1).lower()
            table = tables.get(name)
            if table is None:
                warn('INSERT 未找到对应表定义: %s' % name)
                i += 1
                continue
            start = line.index('VALUES ') + len('VALUES ')
            payload = raw_line[raw_line.index(b'VALUES ') + 7:]
            if not payload.rstrip().endswith(b';'):
                warn('INSERT 语句不是以分号结尾: %s' % name)
            payload = payload.rstrip().rstrip(b';')
            table.rows.extend(parse_insert_values(payload))
            i += 1
            continue

        # 其它语句忽略
        i += 1

    # 生成数据部分
    for name in order:
        table = tables[name]
        if not table.rows:
            continue
        cols = [c for c, _ in table.columns]
        bytea_flags = [f for _, f in table.columns]
        col_list = ', '.join(qident(c) for c in cols)
        for row in table.rows:
            if len(row) != len(cols):
                warn('表 %s 列数不匹配: 期望 %d 实际 %d' % (name, len(cols), len(row)))
                continue
            values = [pg_value(k, v, bytea_flags[idx]) for idx, (k, v) in enumerate(row)]
            out.append('INSERT INTO %s (%s) VALUES (%s);' % (name, col_list, ', '.join(values)))

        if table.identity_col:
            idx = cols.index(table.identity_col)
            nums = [int(r[idx][1]) for r in table.rows if r[idx][0] == 'num' and r[idx][1].isdigit()]
            if nums:
                out.append('ALTER TABLE %s ALTER COLUMN %s RESTART WITH %d;'
                           % (name, qident(table.identity_col), max(nums) + 1))

    header = [
        '-- MaxKey 4.2.0 KingbaseES 初始化脚本',
        '-- 由 sql/kingbase/convert_from_mysql.py 自动生成，请勿手工修改',
        '-- 源文件: %s' % src,
        '',
        "SET client_encoding = 'UTF8';",
        "SET standard_conforming_strings = on;",
        '',
    ]

    with open(dst, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(header + out) + '\n')

    print('表数量: %d' % len(order))
    print('INSERT 行数: %d' % sum(len(tables[t].rows) for t in order))
    print('输出: %s' % dst)
    if warnings:
        print('\n警告 %d 条:' % len(warnings))
        for w in sorted(set(warnings))[:50]:
            print('  -', w)


if __name__ == '__main__':
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(1)
    main(sys.argv[1], sys.argv[2])
